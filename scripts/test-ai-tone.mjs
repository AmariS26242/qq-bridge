// ai-tone 去 AI 味后处理回归测试（纯函数，不依赖 SnowLuma / DSH / QQ）。
// 用法：node scripts/test-ai-tone.mjs
import { deslopChatText, listRules, listBannedWords } from '../src/ai-tone.js';

let failed = 0;
const eq = (name, got, want) => {
  const ok = got === want;
  if (!ok) failed += 1;
  console.log(`${ok ? '✅' : '❌'} ${name}${ok ? '' : `\n   got : ${JSON.stringify(got)}\n   want: ${JSON.stringify(want)}`}`);
};
const has = (name, cond, extra = '') => {
  if (!cond) failed += 1;
  console.log(`${cond ? '✅' : '❌'} ${name}${cond ? '' : ' — ' + extra}`);
};
const tone = (s, o) => deslopChatText(s, o).text;

// ── A. 心理师腔：用户点名的那一句 ────────────────────────────────────────
eq('「这话听着挺沉的」被整句删掉', tone('这话听着挺沉的，最近是不是遇到啥事了'), '最近是不是遇到啥事了');
eq('「这话听着挺沉」结尾无标点也不残留', tone('这话听着挺沉'), '嗯');
eq('「我能感觉到你最近挺累的」去掉监听声明', tone('我能感觉到你最近挺累的'), '你最近挺累的');
eq('「听起来你最近不太顺」只删包装', tone('听起来你最近不太顺'), '你最近不太顺');
eq('「我理解你的感受」换成「懂」', tone('我理解你的感受'), '懂');
eq('「你的感受是合理的」被删空 → 兜底', tone('你的感受是合理的'), '嗯');
eq('「稳稳地接住你的情绪」', tone('我会稳稳地接住你的情绪'), '我会');
eq('「情绪价值」', tone('给你提供情绪价值'), '给你');
eq('「狠狠共情了」', tone('狠狠共情了'), '了', '');

// ── B. 总结 / 拔高 / 连接词 ─────────────────────────────────────────────
eq('「首先，」开头被删', tone('首先，这个方案不行'), '这个方案不行');
eq('「另外，」开头被删', tone('另外，明天可能下雨'), '明天可能下雨');
eq('「综上所述，」+ 句末句号', tone('综上所述，就这样吧。'), '就这样吧');
eq('「值得注意的是」被删', tone('值得注意的是，他昨天没来'), '他昨天没来');
eq('「总而言之呢」', tone('总而言之呢，先这样'), '先这样');
eq('「让我们一起…」不再整句删（防误伤「让我们去吃饭」）', tone('让我们一起为未来加油！'), '让我们一起为未来加油！');
eq('「未来可期」', tone('未来可期'), '嗯', '');

// ── C. 客服腔 ───────────────────────────────────────────────────────────
eq('「希望对你有帮助」被删', tone('希望对你有帮助。'), '嗯');
eq('「有问题随时问我」被删', tone('有问题随时问我'), '嗯', '');
eq('「祝你周末愉快」被删', tone('祝你周末愉快'), '嗯', '');
eq('「以下是…：」被删', tone('以下是几个建议：'), '嗯');

// ── D. Markdown 残留 ────────────────────────────────────────────────────
eq('粗体星号被去掉', tone('**重点**：明天别迟到'), '重点：明天别迟到');
eq('斜体星号被去掉', tone('*小声* 说一句'), '小声 说一句');
eq('行内代码被去掉', tone('用 `pnpm` 装'), '用 pnpm 装');
eq('列表符被去掉', tone('- 甲\n- 乙'), '甲\n乙');
eq('编号列表被去掉', tone('1. 甲\n2. 乙'), '甲\n乙');
eq('标题符被去掉', tone('## 今日'), '今日');

// ── E. 黑话 1:1 替换 / 程度副词 ─────────────────────────────────────────
eq('「赋能」→「帮」', tone('赋能团队'), '帮团队');
eq('「打造闭环」→ 人话', tone('打造完整流程'), '做完整流程');
eq('「非常不错」→「不错」', tone('非常不错'), '不错');
has('「非常规」不被误删', tone('非常规操作') === '非常规操作');

// ── E2. 书面腔 → 口语腔 ────────────────────────────────────────────────
eq('「因此」→「所以」', tone('因此我决定不去'), '所以我决定不去');
eq('「例如」→「比如」', tone('例如这种情况'), '比如这种情况');
eq('「以及」→「和」', tone('你以及我'), '你和我');
eq('「是否」→「是不是」', tone('是否要来'), '是不是要来');
eq('「许多」→「好多」', tone('许多人都不去'), '好多人都不去');
eq('「进行了讨论」→「讨论」', tone('我们进行了讨论'), '我们讨论');
eq('「进一步」→「再」', tone('进一步确认一下'), '再确认一下');
eq('「但是对于」→「但对」', tone('很好但是对于我来说'), '很好但对我来说');

// ── F. 不能误伤的正常聊天 ──────────────────────────────────────────────
const naturals = [
  '今天食堂的菜好咸',
  '这电影我看了三遍',
  '嗯，懂了',
  '明天几点集合？',
  '我先去洗澡了，等下再聊',
  '你在干嘛呢'
];
for (const s of naturals) eq(`正常聊天不动：${s}`, tone(s), s);

// ── F2. 句首确认式开场（「行，……」）────────────────────────────────────
eq('「行，」开场被删', tone('行，那就这么定了'), '那就这么定了');
eq('「好的，」开场被删', tone('好的，我看一下'), '我看一下');
eq('「没问题，」开场被删', tone('没问题，这就来'), '这就来');
eq('「收到，」开场被删', tone('收到，明天见'), '明天见');
eq('连续开场一起删', tone('行，好的，那就这样'), '那就这样');
eq('整条只有「行，」→ 兜底', tone('行，'), '嗯');
eq('「行」单独一条不动', tone('行'), '行');
eq('「行吧」不动（带语气）', tone('行吧，听你的'), '行吧，听你的');
eq('句中「行，」不动', tone('这样行，不过要快点'), '这样行，不过要快点');
eq('「行吗」不动', tone('行吗'), '行吗');
eq('stripAgreeOpener=false 保留', tone('行，那就这样', { stripAgreeOpener: false }), '行，那就这样');

// ── G. 配置行为 ────────────────────────────────────────────────────────
eq('enabled=false 直接返回原文', tone('这话听着挺沉', { enabled: false }), '这话听着挺沉');
eq('keepPhrases 豁免', tone('小鲸鱼的感受', { keepPhrases: ['小鲸鱼'] }), '小鲸鱼的感受', '');
eq('extraPhrases 删除', tone('这也太离谱了吧', { extraPhrases: ['太离谱'] }), '这也了吧');
eq('extraPhrases 替换语法', tone('这也太离谱了', { extraPhrases: ['太离谱=>离谱'] }), '这也离谱了');
eq('空字符串', tone(''), '');
has('stripTrailingPeriod=false 保留句号', tone('就这样吧。', { stripTrailingPeriod: false }) === '就这样吧。');

// ── H. 幂等：过滤两次和一次结果一致 ────────────────────────────────────
const samples = [
  '这话听着挺沉的，我理解你的感受。首先，建议你早点睡。**希望**对你有帮助！',
  '说白了，**非常重要**的一件事：明天九点开会。',
  '综上所述，赋能团队，打造闭环，打造完整流程。'
];
for (const s of samples) eq(`幂等：${s.slice(0, 12)}…`, tone(tone(s)), tone(s));

// ── I. 规则表自检 ──────────────────────────────────────────────────────
const rules = listRules();
const banned = listBannedWords();
has('规则数量 ≥ 25', rules.length >= 25, `实际 ${rules.length}`);
has('规则 id 不重复', new Set(rules.map((r) => r.id)).size === rules.length);
has('内置屏蔽词 ≥ 20', banned.words.length >= 20);

console.log(`\n${failed === 0 ? '全部通过' : `${failed} 项失败`}`);
process.exit(failed === 0 ? 0 : 1);
